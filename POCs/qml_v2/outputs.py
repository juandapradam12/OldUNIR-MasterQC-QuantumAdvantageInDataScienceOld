"""Rutas del repositorio y salida común de los protocolos justos (CSV, informe, CLI).

Los módulos ``classification``, ``regression``, ``anomaly``, ``clustering`` y ``timeseries``
comparten el mismo patrón de ejecución: resumir cada dataset, escribir sus CSV, componer un
informe Markdown en ``BUSINESS/`` y exponer la misma interfaz de línea de comandos.
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Callable, Sequence
from dataclasses import asdict
from pathlib import Path
from typing import Any

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
POCS_DIR = Path(__file__).resolve().parents[1]


def repo_paths() -> dict[str, Path]:
    return {
        "telco": POCS_DIR / "data" / "input" / "telco_customer_churn.csv",
        "skg": REPO_ROOT / "Datos" / "incidents_movility.csv",
        "metrics": POCS_DIR / "data" / "output" / "metrics",
    }


def metrics_dir() -> Path:
    path = repo_paths()["metrics"]
    path.mkdir(parents=True, exist_ok=True)
    return path


def report_header(title: str, module: str, notes: Sequence[str], cfg: Any) -> list[str]:
    return [
        f"# {title}",
        "",
        f"Generated by `python -m qml_v2.{module}`.",
        *notes,
        "",
        f"Config: `{json.dumps(asdict(cfg))}`",
        "",
    ]


def record_dataset(
    name: str,
    rows: list,
    summarize: Callable[[list], pd.DataFrame],
    advantage_report: Callable[[pd.DataFrame], str],
    *,
    stem: str,
    report: list[str],
) -> pd.DataFrame:
    """Resume un dataset, escribe ``{stem}_{name}[_raw].csv`` y añade su sección al informe."""
    directory = metrics_dir()
    raw = pd.DataFrame([asdict(r) for r in rows])
    raw.insert(0, "dataset", name)
    raw.to_csv(directory / f"{stem}_{name}_raw.csv", index=False)

    summary = summarize(rows)
    summary.insert(0, "dataset", name)
    summary.to_csv(directory / f"{stem}_{name}.csv", index=False)

    advantage = advantage_report(summary)
    print(summary.to_string(index=False))
    print(advantage)
    report += [f"## {name}", "", "```", advantage, "```", "", "```", summary.to_string(index=False), "```", ""]
    return summary


def finish_run(report: list[str], cfg: Any, *, report_file: str, config_file: str) -> Path:
    """Escribe el informe en ``BUSINESS/`` y la configuración junto a las métricas."""
    (metrics_dir() / config_file).write_text(json.dumps(asdict(cfg), indent=2))
    path = REPO_ROOT / "BUSINESS" / report_file
    path.write_text("\n".join(report) + "\n")
    print(f"\nWrote {path}")
    return path


def make_parser(
    description: str,
    default_datasets: str,
    flags: Sequence[str] = ("n_total", "n_repeats"),
) -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=description)
    parser.add_argument("--quick", action="store_true")
    for flag in flags:
        parser.add_argument(f"--{flag.replace('_', '-')}", type=int, default=None)
    parser.add_argument("--datasets", default=default_datasets, help="Comma-separated dataset names")
    return parser


def apply_overrides(cfg: Any, args: argparse.Namespace, flags: Sequence[str]) -> Any:
    """Sobrescribe en ``cfg`` los parámetros indicados por CLI."""
    for flag in flags:
        value = getattr(args, flag)
        if value is not None:
            setattr(cfg, flag, value)
    return cfg


def dataset_names(args: argparse.Namespace) -> tuple[str, ...]:
    return tuple(s.strip() for s in args.datasets.split(",") if s.strip())
